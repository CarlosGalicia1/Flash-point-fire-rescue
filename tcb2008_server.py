from http.server import BaseHTTPRequestHandler, HTTPServer
import logging
import json

class Server(BaseHTTPRequestHandler):
    request_count = 0

    def _set_response(self):
        self.send_response(200)
        self.send_header('Content-type', 'application/json')
        self.end_headers()

    def do_GET(self):
        self._set_response()
        self.wfile.write("GET request for {}".format(self.path).encode('utf-8'))

    def do_POST(self):
        Server.request_count += 1
        logging.info(f"Recieved POST request #{Server.request_count}")
        tiles = model.initialDictionary
        tiles_serialized = {f"{k[0]},{k[1]}": v for k, v in tiles.items()}

        if Server.request_count == 1:
            self._set_response()
            self.wfile.write(json.dumps(tiles_serialized).encode('utf-8'))
            logging.info("Sent tiles")
        else:
            self._set_response()
            self.wfile.write(parsedJSON.encode('utf-8'))
            logging.info("Sent moves")
            Server.request_count = 0


def run(server_class=HTTPServer, handler_class=Server, port=8585):
    logging.basicConfig(level=logging.INFO)
    server_address = ('', port)
    httpd = server_class(server_address, handler_class)
    logging.info("Starting httpd...\n") # HTTPD is HTTP Daemon!

    try:
        httpd.serve_forever()
    except KeyboardInterrupt:   # CTRL+C stops the server
        pass
    httpd.server_close()
    logging.info("Stopping httpd...\n")

if __name__ == '__main__':
    from sys import argv

    if len(argv) == 2:
        run(port=int(argv[1]))
    else:
        run()

