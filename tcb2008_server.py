    def step(self):
        print(f"AGENT: {self.unique_id}")

        self.move_index = 1
        self.model.replenishPOIs()
        print(f"Carreando {self.carrying}")

        if self.carrying == False:
            self.calculatenearest()
            self.dijkstra_to_nearest(self.model.graph, self.pos, self.nearestPOI)
            goalPos = self.nearestPOI
        else:
            self.calculatenearest()
            self.dijkstra_to_nearest(self.model.graph, self.pos, self.nearestEntrypoint)
            goalPos = self.nearestEntrypoint



        print(f"Move index: {self.move_index}")
        if self.move_index < len(self.movesToGoal):
            print(f"Siguiente posicion: {self.movesToGoal[self.move_index]}")

        print(f"Energy: {self.energy}")
        print(f"Len(moves to poi): {len(self.movesToGoal)}")
        while self.energy > 0 and self.move_index < len(self.movesToGoal) and self.canAdvance == True:

            move = self.movesToGoal[self.move_index]
            # itera en la lista de movesToGoal empezando por el segundo elemento

            current_tile = [obj for obj in self.model.grid.get_cell_list_contents([self.pos]) if isinstance(obj, Tile)][0]
            next_tile = [obj for obj in self.model.grid.get_cell_list_contents([move]) if isinstance(obj, Tile)][0]
            # Evalua si existe algun tipo de bloqueo entre la posicion actual
            print(f"Posicion actual: {self.pos}")
            print(f"Siguiente posicion: {move}")


            match self.model.graph[self.pos][move]:
                case 1:
                    self.isBlocked = False
                case 2:
                    self.isBlocked = True
                    blocker = "Door"
                    print("Blocked by door")
                case 3:
                    self.isBlocked = True
                    blocker = "Damaged Wall"
                    print("Blocked by Damaged Wall")
                case 5:
                    self.isBlocked = True
                    blocker = "Wall"
                    print("Blocked by Wall")

            if self.isBlocked == False and self.canAdvance:
                if next_tile.fireStatus == 2:
                    print("Fire detected")
                    if self.energy >= 2:
                        print("Fire extinguished")
                        self.extinguish(move)

                    else:
                        print("Fire couldnt be extinguished in the current turn")
                        self.canAdvance = False
                else:
                    if self.energy>= self.moveCost:
                        # print("Moving")
                        self.move(move)
                        self.move_index += 1
                    else:
                        print("Couldnt move in the current turn")
                        self.canAdvance = False
            elif self.isBlocked == True and self.canAdvance:
                match blocker:
                    case "Door":
                        if self.energy >= 1:
                            print("Door opened")
                            self.manipulateDoor(True, move)
                            self.model.graph[self.pos][move] = 1
                            self.model.graph[move][self.pos] = 1
                        else:
                            print("Door couldnt be opened in the current turn")
                            self.canAdvance = False
                    case "Damaged Wall":
                        if self.energy >= 2:
                            print("Damaged wall destroyed")
                            self.damage(False, move)
                            self.model.graph[self.pos][move] = 1
                            self.model.graph[move][self.pos] = 1
                        else:
                            print("Damaged wall couldnt be destroyed in the current turn")
                            self.canAdvance = False
                    case "Wall":
                        if self.energy >= 4:
                            print("Wall destroyed")
                            self.damage(True, move)
                            self.model.graph[self.pos][move] = 1
                            self.model.graph[move][self.pos] = 1
                        else:
                            print("Wall couldnt be destroyed in the current turn")
                            self.canAdvance = False

            print("Energy: ", self.energy)

        if self.pos == self.nearestPOI:
            self.move_index = 1
            print("Posicion del POI alcanzada")

        if self.pos == self.nearestEntrypoint:
            self.move_index = 1
            print("Posicion del punto de entrada alcanzada")
            self.dropVictim()

        if self.energy <= 0:
            print("Energia terminada")
            self.move_index = 1

        # Reiniciar el nivel de energia para el siguiente turno
        self.energy = 4 + self.energy
        if self.energy > 8:
            self.energy = 8

