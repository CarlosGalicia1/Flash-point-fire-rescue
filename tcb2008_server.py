def get_grid(model):
  grid = np.zeros((model.grid.width, model.grid.height))
  for content, (x, y) in model.grid.coord_iter():
    if content:
      grid[x][y] = 1
  return grid

def match_elements(model):
    grid = np.zeros((model.grid.width, model.grid.height))

    for agent in model.schedule.agents:
        grid[agent.pos[0], agent.pos[1]] = 1

    return grid

